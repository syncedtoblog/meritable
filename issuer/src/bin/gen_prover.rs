use ark_bn254::Fr;
use issuer::crypto;

/// Generates a valid `circuit/Prover.toml` for the current dev issuer key.
///
/// This is a development helper, not a production API. It uses deterministic
/// credential values so the generated proof fixture is reproducible enough for
/// local testing. The signature nonce is still random, so each run produces a
/// different but valid signature.
fn main() {
    let user_address_str = "GA5ZSEJYB37JRC5AVCIA5MOP4RHTM335X2KGX3IHOJAPP5RE34K4KZVN";
    let user_address = crypto::stellar_address_to_field(user_address_str)
        .expect("valid Stellar address");
    let key = crypto::string_to_field("credit_score");
    let value = Fr::from(750u64);
    let salt = Fr::from(123456789u64);

    let commitment = crypto::compute_poseidon_hash_4(&[user_address, key, value, salt])
        .expect("Poseidon commitment");
    let sig = crypto::sign_commitment(commitment);

    println!("# Generated by: cargo run -p issuer --bin gen_prover");
    println!("# Dev issuer address: {user_address_str}");
    println!();
    println!("# Private inputs");
    println!("key = \"{}\"", crypto::field_to_hex(&key));
    println!("value = \"{}\"", crypto::field_to_hex(&value));
    println!("salt = \"{}\"", crypto::field_to_hex(&salt));
    println!("sig_s_lo = \"{}\"", crypto::field_to_hex(&sig.sig_s_lo));
    println!("sig_s_hi = \"{}\"", crypto::field_to_hex(&sig.sig_s_hi));
    println!("sig_e_lo = \"{}\"", crypto::field_to_hex(&sig.sig_e_lo));
    println!("sig_e_hi = \"{}\"", crypto::field_to_hex(&sig.sig_e_hi));
    println!();
    println!("# Public inputs");
    println!("issuer_pubkey_x = \"{}\"", crypto::field_to_hex(&sig.issuer_pubkey_x));
    println!("issuer_pubkey_y = \"{}\"", crypto::field_to_hex(&sig.issuer_pubkey_y));
    println!("user_address = \"{}\"", crypto::field_to_hex(&user_address));
    println!("target_key = \"{}\"", crypto::field_to_hex(&key));
    println!("operator = \"0\"");
    println!("threshold = \"700\"");
    println!("nonce = \"987654\"");
}
